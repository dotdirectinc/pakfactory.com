#!/usr/bin/env node
/**
 * PROD-2733 — `customizationOption.status` drops Coming soon and Discontinued.
 *
 *   coming-soon   →  active       (Eric, 2026-09-30)
 *   discontinued  →  not-active
 *   active        →  unchanged
 *
 * ── Why the values go ───────────────────────────────────────────────────────
 *
 * A discontinued PRODUCT is one box we stopped making, and saying so is fine.
 * A discontinued CUSTOMIZATION reads as a capability we no longer have, which is
 * the opposite of what we sell — we tell customers we can do any customization.
 * Same for coming-soon. So on customizations there is no public "not available"
 * state at all: an option is either offered, or it is internal.
 *
 * product / productLine / productStyle / solution keep all three values, their
 * badges and their notices. This is a customization-only change.
 *
 * ── Why coming-soon becomes ACTIVE, which is the part that was decided ──────
 *
 * Dropping coming-soon leaves no middle state: each of those options becomes
 * either orderable or invisible. There is no third answer. 85 options on
 * development are coming-soon — PET pouch film, PLA blends, holographic foils,
 * foiling and cutting methods — and 72 of them already have a detail page.
 *
 * Eric's call, 2026-09-30: all of them ACTIVE. That follows directly from the
 * reason the value is going — we do not want a customer told that something is
 * on its way rather than available.
 *
 * 🔴 THIS IS A COMMERCIAL CLAIM, NOT A DATA TIDY-UP. 85 materials become
 * orderable the moment the front end reads them. It is recorded here because a
 * migration that quietly makes 85 things purchasable should say so out loud.
 *
 * ── `not-active` is an off switch the model did not have ───────────────────
 *
 * `compatibleCustomizations` and `achieves` are STRONG references, so Sanity
 * refuses to unpublish or delete an option another option points at — and
 * `discontinued` deliberately kept the page LIVE rather than hiding it. There was
 * no way to take an option off the site. 39 of the 38 discontinued plus the
 * retired technical materials are exactly that case.
 *
 * A not-active option stays in the dataset, so every reference to it keeps
 * resolving, and no customer can reach it: every query returning an option gates
 * on status, and every gate is a whitelist that cannot contain `not-active`.
 *
 * ── ⚠️ THE PART THIS SCRIPT CANNOT FIX ──────────────────────────────────────
 *
 * 🔴 The catalog fill must stop emitting the removed values, or they come back.
 * Its review sets are generated by `pakfactory.com-backend/scripts/sanity-fill.mjs`
 * and the fill writes over the API, where `options.list` does not apply. A
 * generator still emitting `coming-soon` would SUCCEED, and those options would
 * vanish from the site while showing an error in Studio. Nothing fails loudly.
 *
 * Re-running this script repairs the data but not the cause.
 *
 * Drafts included (`perspective: 'raw'`) — publishing a stale draft would otherwise
 * restore a removed value on a document this script had already fixed.
 * Idempotent: re-running writes the same values.
 *
 * `--verify` re-reads the dataset and compares VALUES, not counts. Transactions can
 * return before the dataset settles, so a script's own closing tally is not evidence.
 *
 * Written by an agent, RUN BY A HUMAN (AGENTS.md § Sanity content).
 *
 * 🔴 Run it through the register, not the command below:
 *   pnpm sanity:migrate up --dataset <development|production> \
 *     --only 20260930-customization-status --confirm
 *
 * The invocation below is this script's own interface, and is still the right way
 * to take a dry run:
 *   pnpm --filter @pakfactory/studio run migrate:customization-status -- --dataset development
 *   ...                                                                 --dataset development --confirm
 *   ...                                                                 --dataset production --confirm --yes-production
 *   ...                                                                 --dataset production --verify
 *
 * ⚠️ Run in the SAME deploy as the schema change: until it does, every option
 * holding a removed value shows a validation error in Studio.
 */

import { createClient } from '@sanity/client'
import { config as loadEnv } from 'dotenv'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseScriptArgs, describeMode } from './lib/script-args.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, '../../..')
loadEnv({ path: join(repoRoot, '.env.local') })
loadEnv({ path: join(repoRoot, '.env') })
loadEnv({ path: join(repoRoot, 'apps/studio/.env.local'), override: true })

const USAGE = `Usage:
  pnpm --filter @pakfactory/studio run migrate:customization-status -- --dataset <development|production> [--confirm] [--yes-production] [--verify]

  --dataset         REQUIRED. Which dataset to read/write. No env fallback.
  --confirm         Actually write. Without it the run is a dry run.
  --yes-production  Second gate; required to write to production.
  --verify          Read-only. Re-read and compare values; writes nothing.`

const args = parseScriptArgs({ usage: USAGE, flags: ['verify'] })
const { confirm: apply, verify } = args

const PROJECT_ID =
  process.env.NEXT_PUBLIC_SANITY_PROJECT_ID || process.env.SANITY_STUDIO_PROJECT_ID || '8293wrxp'
const DATASET = args.dataset
const TOKEN =
  process.env.SANITY_API_WRITE_TOKEN || process.env.SANITY_API_READ_TOKEN || process.env.SANITY_TOKEN

if (!TOKEN) {
  console.error('❌  Missing Sanity token in .env.local')
  process.exit(1)
}
if (apply && !(process.env.SANITY_API_WRITE_TOKEN || process.env.SANITY_TOKEN)) {
  console.error('❌  --confirm needs a WRITE token.')
  process.exit(1)
}

const client = createClient({
  projectId: PROJECT_ID,
  dataset: DATASET,
  apiVersion: process.env.NEXT_PUBLIC_SANITY_API_VERSION || '2025-01-01',
  token: TOKEN,
  useCdn: false,
  perspective: 'raw',
})

const label = (d) => `${d.title || d._id}${d.isDraft ? ' (draft)' : ''}`

/** The whole mapping, in one place. `null` means "no rule for this value". */
const NEXT = {
  'active': 'active',
  'not-active': 'not-active',
  'coming-soon': 'active',
  'discontinued': 'not-active',
}

async function main() {
  console.log('\n🔀  customizationOption.status → Active / Not active (PROD-2733)')
  console.log(`    project=${PROJECT_ID} dataset=${DATASET} mode=${describeMode(args)}\n`)

  const docs = await client.fetch(
    `*[_type == "customizationOption"]{
       _id, title, status, appearsIn,
       "isDraft": _id in path("drafts.**")
     } | order(title asc)`,
  )

  if (!docs.length) {
    console.log(`✅  Nothing to do — ${DATASET} holds no customizationOption documents.\n`)
    return
  }

  // ── The gate: a status this script has no rule for. `status` is required in the
  //    schema, so an unset or unknown one means the data diverged from it, and
  //    guessing would decide whether 85 materials are orderable.
  const unmapped = docs.filter((d) => !(d.status in NEXT))
  if (unmapped.length) {
    console.error(`❌  ${unmapped.length} Option(s) carry a status this migration has no rule for:`)
    unmapped.forEach((d) => console.error(`     ${d._id}  ${label(d)}  status=${JSON.stringify(d.status)}`))
    console.error('    `status` is required in the schema, so this means the data diverged from it.')
    console.error('    Set them by hand, or add the rule deliberately. Nothing written.')
    process.exit(1)
  }

  const plan = docs.map((d) => ({ ...d, next: NEXT[d.status] }))

  if (verify) {
    const wrong = plan.filter((p) => p.status !== p.next)
    console.log(`Checked ${plan.length} Option(s) against the intended mapping.`)
    if (!wrong.length) {
      console.log('✅  Every Option carries Active or Not active.\n')
      return
    }
    console.error(`❌  ${wrong.length} Option(s) still hold a removed value:`)
    wrong.forEach((p) => console.error(`     ${label(p)}: status=${JSON.stringify(p.status)} (want ${JSON.stringify(p.next)})`))
    process.exit(1)
  }

  const becomingActive = plan.filter((p) => p.status === 'coming-soon')
  const becomingOff = plan.filter((p) => p.status === 'discontinued')
  console.log(`${plan.length} Option(s) (drafts included):`)
  console.log(`   coming-soon  → Active       ${becomingActive.length}`)
  console.log(`   discontinued → Not active   ${becomingOff.length}`)
  console.log(`   already Active / Not active ${plan.length - becomingActive.length - becomingOff.length}`)

  // Named individually. Making something orderable is a commercial claim, and
  // removing it from the site is a customer-visible withdrawal — both are worth
  // reading rather than counting.
  if (becomingActive.length) {
    console.log(`\n🔴 Becoming ACTIVE — orderable once the front end reads them:`)
    becomingActive.forEach((p) => console.log(`   • ${label(p)}`))
  }
  if (becomingOff.length) {
    console.log(`\nBecoming NOT ACTIVE — no configurator, no library, no page; still a resolvable reference:`)
    becomingOff.forEach((p) => console.log(`   • ${label(p)}`))
  }

  const tx = client.transaction()
  let writes = 0
  for (const p of plan) {
    if (p.status === p.next) continue
    tx.patch(p._id, (patch) => patch.set({ status: p.next }))
    writes++
  }

  if (!writes) {
    console.log(`\n✅  Nothing to do — ${DATASET} already carries only Active and Not active.\n`)
    return
  }
  if (!apply) {
    console.log(`\n${writes} patch(es) pending on ${DATASET}. DRY-RUN only — re-run with \`--confirm\` (production also needs \`--yes-production\`).\n`)
    return
  }

  // `visibility: 'sync'` — an async commit returns before the dataset settles, so
  // the check below would read stale state and report success either way.
  await tx.commit({ visibility: 'sync' })
  console.log(`\n✅  Applied ${writes} patch(es) in ${DATASET}.`)

  const left = await client.fetch(
    `count(*[_type == "customizationOption" && !(status in ["active", "not-active"])])`,
  )
  console.log(`    ${left} Option(s) still hold a removed value (want 0).`)
  console.log(`    ⚠️  The catalog fill will re-introduce them unless its generator stops emitting them.`)
  console.log(`    Re-run with \`--verify\` to compare values rather than counts.\n`)
  if (left > 0) process.exit(1)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
